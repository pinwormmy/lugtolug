// Print SQL that moves D1 watch rows to the current slug rule (src/lib/watchText.ts
// slugify). `npm run db:seed:remote` already rewrites every seed row by id, so this
// covers only the rows the seed does not carry: operator approvals not yet folded
// into the seed and archived duplicates that still suppress seed matches by slug.
//
//   node scripts/generate-reslug-sql.mjs                 # query production D1, print SQL
//   node scripts/generate-reslug-sql.mjs --input=rows.json   # use {"watches":[...]} instead
//   node scripts/generate-reslug-sql.mjs > /tmp/reslug.sql && \
//     npx wrangler d1 execute lugtolug-finder --remote --file=/tmp/reslug.sql
//
// Placeholder reference slugs (seed-tmp-*, retired-*, archived-*) are kept; only brand and
// model slugs change on those rows. Rows whose new slugs would collide with
// another row are reported on stderr and skipped so idx_watches_slugs stays valid.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { getWatchSlugs } from "../src/lib/watchText.ts";

const DATABASE = "lugtolug-finder";
const PLACEHOLDER_REFERENCE_SLUG = /^(seed-tmp-|retired-|archived-)/;

function argumentValue(name) {
  const prefix = `--${name}=`;
  return process.argv.find((argument) => argument.startsWith(prefix))?.slice(prefix.length);
}

function d1Query(sql) {
  const output = execFileSync("npx", ["wrangler", "d1", "execute", DATABASE, "--remote", "--json", "--command", sql], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024
  });
  const start = output.indexOf("[");
  if (start === -1) throw new Error(`Unexpected wrangler output:\n${output}`);
  const [result] = JSON.parse(output.slice(start));
  if (!result?.success) throw new Error(`D1 query failed:\n${output}`);
  return result.results;
}

function loadRows() {
  const inputPath = argumentValue("input");
  if (inputPath) return JSON.parse(readFileSync(resolve(inputPath), "utf8")).watches ?? [];
  return d1Query("SELECT id, brand, model, reference, brand_slug, model_slug, reference_slug, status FROM watches");
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = loadRows();
const routeOwners = new Map(rows.map((row) => [`${row.brand_slug}/${row.model_slug}/${row.reference_slug}`, row.id]));
const updates = [];
const skipped = [];

for (const row of rows) {
  const slugs = getWatchSlugs({ brand: row.brand ?? "", model: row.model ?? "", reference: row.reference ?? "" });
  const referenceSlug = PLACEHOLDER_REFERENCE_SLUG.test(row.reference_slug) ? row.reference_slug : slugs.referenceSlug;
  if (row.brand_slug === slugs.brandSlug && row.model_slug === slugs.modelSlug && row.reference_slug === referenceSlug) continue;

  const route = `${slugs.brandSlug}/${slugs.modelSlug}/${referenceSlug}`;
  const owner = routeOwners.get(route);
  if (owner != null && owner !== row.id) {
    skipped.push(`${row.id} (${row.brand} ${row.model} ${row.reference}) -> ${route} is already used by ${owner}`);
    continue;
  }

  routeOwners.delete(`${row.brand_slug}/${row.model_slug}/${row.reference_slug}`);
  routeOwners.set(route, row.id);
  updates.push(
    `UPDATE watches SET brand_slug = ${sqlString(slugs.brandSlug)}, model_slug = ${sqlString(slugs.modelSlug)}, ` +
      `reference_slug = ${sqlString(referenceSlug)}, updated_at = CURRENT_TIMESTAMP WHERE id = ${Number(row.id)};`
  );
}

if (skipped.length > 0) {
  console.error(`Skipped ${skipped.length} row(s) whose new route is taken:\n  ${skipped.join("\n  ")}`);
}
console.error(`${updates.length} of ${rows.length} rows need new slugs.`);
process.stdout.write(
  [`-- Generated by scripts/generate-reslug-sql.mjs (${updates.length} rows). Do not edit by hand.`, ...updates, ""].join("\n")
);
